// Create a reverse mapping dictionary for fast matching
const textToFrMap = new Map<string, string>();
const textToEnMap = new Map<string, string>();

Object.values(translations).forEach(({ en, fr }) => {
  textToFrMap.set(en.trim().toLowerCase(), fr);
  textToEnMap.set(fr.trim().toLowerCase(), en);
});

/**
 * Get translation for a specific string key or return string if missing
 */
export function getTranslation(text: string, targetLang: Language): string {
  if (!text || typeof text !== "string") return text;
  const trimmed = text.trim();
  if (!trimmed) return text;
  const lower = trimmed.toLowerCase();

  if (targetLang === "fr") {
    if (textToFrMap.has(lower)) {
      return textToFrMap.get(lower)!;
    }
  } else {
    if (textToEnMap.has(lower)) {
      return textToEnMap.get(lower)!;
    }
  }

  return text;
}
