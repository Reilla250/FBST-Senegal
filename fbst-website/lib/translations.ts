// Create normalized search maps
const textToFrMap = new Map<string, string>();
const textToEnMap = new Map<string, string>();

function normalize(str: string): string {
  return str
    .replace(/[\u2018\u2019']/g, "'")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

Object.values(translations).forEach(({ en, fr }) => {
  textToFrMap.set(normalize(en), fr);
  textToEnMap.set(normalize(fr), en);
});

/**
 * Robust string translation helper
 */
export function getTranslation(text: string, targetLang: Language): string {
  if (!text || typeof text !== "string") return text;
  const norm = normalize(text);
  if (!norm) return text;

  if (targetLang === "fr") {
    if (textToFrMap.has(norm)) {
      return textToFrMap.get(norm)!;
    }
  } else {
    if (textToEnMap.has(norm)) {
      return textToEnMap.get(norm)!;
    }
  }

  return text;
}
